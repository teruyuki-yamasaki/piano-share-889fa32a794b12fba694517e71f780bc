const messages = { ja, en };
let currentLanguage = 'ja';
export function getLanguage() {
    return currentLanguage;
}
export function setLanguage(language) {
    currentLanguage = language === 'en' ? 'en' : 'ja';
}
export function t(key, vars = {}) {
    const text = messages[currentLanguage][key] ?? ja[key] ?? key;
    return text.replace(/\{(\w+)\}/g, (_, name) => String(vars[name] ?? `{${name}}`));
}
export function applyLanguage(root = document) {
    document.documentElement.lang = currentLanguage;
    root.querySelectorAll('[data-i18n]').forEach((el) => {
        el.textContent = t(el.dataset.i18n);
    });
    root.querySelectorAll('[data-i18n-title]').forEach((el) => {
        el.title = t(el.dataset.i18nTitle);
    });
    root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => {
        el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel));
    });
}
/** 読み込み時に日本語で付けたパート名（右手・トラック 2 など）を表示言語に合わせる */
export function partLabel(name, player) {
    if (player)
        return t('playerPart', { player: playerLabel(player), part: partLabel(name) });
    const fixed = { 右手: 'rightHand', 左手: 'leftHand', 主旋律: 'melodyPart', 伴奏: 'accompPart' };
    if (fixed[name])
        return t(fixed[name]);
    const m = /^(チャンネル|トラック) (\d+)$/.exec(name);
    if (m)
        return t(m[1] === 'チャンネル' ? 'channel' : 'track', { n: m[2] });
    return name;
}
/** 連弾の奏者の名前（MusicXML の <part-name>。PRIMO / Secondo / プリモ など）を表示言語に合わせる */
export function playerLabel(name) {
    if (/primo|プリモ/i.test(name))
        return t('primo');
    if (/secondo|セコンド/i.test(name))
        return t('secondo');
    return name;
}
export function localized(e, field) {
    return (currentLanguage === 'en' ? e.en?.[field] : undefined) ?? e[field] ?? '';
}
